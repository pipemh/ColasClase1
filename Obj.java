public class Obj{
    int Name;
    int Turno;
    int Cant;
    double price;
    int State;
    
    public Obj() {
    }

    public int getName() {
        return Name;
    }

    public void setName(int name) {
        Name = name;
    }

    public int getTurno() {
        return Turno;
    }

    public void setTurno(int turno) {
        Turno = turno;
    }

    public int getCant() {
        return Cant;
    }

    public void setCant(int cant) {
        Cant = cant;
    }

    public double getPrice() {
        return price;
    }

    public void setPrice(double price) {
        this.price = price;
    }

    public int getState() {
        return State;
    }

    public void setState(int state) {
        State = state;
    }

    

    
}